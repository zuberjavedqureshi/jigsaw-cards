import 'dart:math' as math;
import 'dart:ui';

/// The picture a puzzle is cut from. Pieces render their region of it by
/// clipping and translating, so implementations only paint the full scene.
abstract interface class PuzzleArtwork {
  /// Native size of the illustration. The board uses this aspect ratio so
  /// tiles are never stretched.
  Size get sourceSize;

  /// Paints the full scene into a canvas of [size]. Callers always pass
  /// [sourceSize] (scaled uniformly via the canvas transform).
  void paint(Canvas canvas, Size size);
}

/// **TEMPORARY PLACEHOLDER ARTWORK.** A code-drawn storybook night scene
/// used until real puzzle art exists. It is not final art, was not
/// downloaded or generated by a tool, and should be replaced by real assets
/// (an image-backed [PuzzleArtwork]) when the art pipeline is ready.
class PlaceholderStorybookArtwork implements PuzzleArtwork {
  const PlaceholderStorybookArtwork();

  /// Square: the scene mixes width-relative sizes with height-relative
  /// positions, so it is only undistorted at a 1:1 aspect ratio.
  @override
  Size get sourceSize => const Size(1024, 1024);

  @override
  void paint(Canvas canvas, Size size) {
    final w = size.width;
    final h = size.height;
    Offset at(double x, double y) => Offset(x * w, y * h);

    // Sky: deep night blue to dusky rose at the horizon.
    canvas.drawRect(
      Offset.zero & size,
      Paint()
        ..shader = Gradient.linear(
          at(0, 0),
          at(0, 0.66),
          const [
            Color(0xFF141A45),
            Color(0xFF3D2F7A),
            Color(0xFF8E5A9E),
            Color(0xFFF0A48C),
          ],
          const [0, 0.35, 0.7, 1],
        ),
    );

    // Stars (fixed pseudo-random pattern).
    final star = Paint()..color = const Color(0xFFFFF4D6);
    final rnd = math.Random(7);
    for (var i = 0; i < 46; i++) {
      final x = rnd.nextDouble();
      final y = rnd.nextDouble() * 0.48;
      final r = (0.002 + rnd.nextDouble() * 0.005) * w;
      canvas.drawCircle(at(x, y), r, star);
    }
    // A few sparkle stars.
    final sparkle = Paint()
      ..color = const Color(0xFFFFE9A8)
      ..strokeWidth = 0.004 * w
      ..strokeCap = StrokeCap.round;
    for (final (x, y) in const [(0.12, 0.10), (0.55, 0.07), (0.38, 0.24)]) {
      final s = 0.018 * w;
      final c = at(x, y);
      canvas.drawLine(c.translate(-s, 0), c.translate(s, 0), sparkle);
      canvas.drawLine(c.translate(0, -s), c.translate(0, s), sparkle);
    }

    // Moon with glow (crescent).
    final moon = at(0.78, 0.17);
    canvas.drawCircle(moon, 0.14 * w, Paint()..color = const Color(0x33FFE7A3));
    canvas.drawCircle(
      moon,
      0.085 * w,
      Paint()..color = const Color(0xFFFFE7A3),
    );
    canvas.drawCircle(
      moon.translate(0.035 * w, -0.02 * w),
      0.075 * w,
      Paint()..color = const Color(0xFF2E2768),
    );

    // Distant mountains.
    final mountains = Path()
      ..moveTo(0, 0.62 * h)
      ..lineTo(0.12 * w, 0.47 * h)
      ..lineTo(0.24 * w, 0.58 * h)
      ..lineTo(0.42 * w, 0.42 * h)
      ..lineTo(0.6 * w, 0.57 * h)
      ..lineTo(0.76 * w, 0.46 * h)
      ..lineTo(w, 0.6 * h)
      ..lineTo(w, h)
      ..lineTo(0, h)
      ..close();
    canvas.drawPath(mountains, Paint()..color = const Color(0xFF5A3E86));

    // Back hill.
    final backHill = Path()
      ..moveTo(0, 0.66 * h)
      ..quadraticBezierTo(0.3 * w, 0.52 * h, 0.62 * w, 0.64 * h)
      ..quadraticBezierTo(0.85 * w, 0.72 * h, w, 0.62 * h)
      ..lineTo(w, h)
      ..lineTo(0, h)
      ..close();
    canvas.drawPath(backHill, Paint()..color = const Color(0xFF2F6B55));

    _castle(canvas, w, h);

    // Front hill.
    final frontHill = Path()
      ..moveTo(0, 0.82 * h)
      ..quadraticBezierTo(0.45 * w, 0.68 * h, w, 0.8 * h)
      ..lineTo(w, h)
      ..lineTo(0, h)
      ..close();
    canvas.drawPath(
      frontHill,
      Paint()
        ..shader = Gradient.linear(at(0, 0.7), at(0, 1), const [
          Color(0xFF4F9A63),
          Color(0xFF2C6B45),
        ]),
    );

    // Winding path from the bottom towards the castle.
    final path = Path()
      ..moveTo(0.46 * w, h)
      ..cubicTo(0.62 * w, 0.9 * h, 0.2 * w, 0.82 * h, 0.3 * w, 0.66 * h);
    canvas.drawPath(
      path,
      Paint()
        ..color = const Color(0xFFE8CF9A)
        ..style = PaintingStyle.stroke
        ..strokeWidth = 0.045 * w
        ..strokeCap = StrokeCap.round,
    );

    _tree(canvas, at(0.82, 0.76), w);
    _tree(canvas, at(0.68, 0.8), w * 0.7);

    // Fireflies.
    final firefly = Paint()..color = const Color(0xFFFFF27A);
    for (final (x, y) in const [
      (0.15, 0.9),
      (0.58, 0.86),
      (0.92, 0.93),
      (0.08, 0.74),
      (0.5, 0.75),
    ]) {
      canvas.drawCircle(
        at(x, y),
        0.012 * w,
        Paint()..color = const Color(0x55FFF27A),
      );
      canvas.drawCircle(at(x, y), 0.005 * w, firefly);
    }
  }

  void _castle(Canvas canvas, double w, double h) {
    final stone = Paint()..color = const Color(0xFF3B3566);
    final roof = Paint()..color = const Color(0xFFB4536B);
    final window = Paint()..color = const Color(0xFFFFD36E);
    Rect r(double l, double t, double rr, double b) =>
        Rect.fromLTRB(l * w, t * h, rr * w, b * h);
    canvas.drawRect(r(0.2, 0.5, 0.42, 0.64), stone);
    for (final (l, rr, t) in const [
      (0.17, 0.24, 0.42),
      (0.28, 0.34, 0.36),
      (0.38, 0.45, 0.44),
    ]) {
      canvas.drawRect(r(l, t, rr, 0.64), stone);
      canvas.drawPath(
        Path()
          ..moveTo(l * w, t * h)
          ..lineTo((l + rr) / 2 * w, (t - 0.08) * h)
          ..lineTo(rr * w, t * h)
          ..close(),
        roof,
      );
      canvas.drawRect(
        r((l + rr) / 2 - 0.008, t + 0.04, (l + rr) / 2 + 0.008, t + 0.07),
        window,
      );
    }
    // Gate.
    canvas.drawRRect(
      RRect.fromRectAndCorners(
        r(0.29, 0.57, 0.33, 0.64),
        topLeft: Radius.circular(0.02 * w),
        topRight: Radius.circular(0.02 * w),
      ),
      Paint()..color = const Color(0xFF241F45),
    );
  }

  void _tree(Canvas canvas, Offset base, double scale) {
    canvas.drawRect(
      Rect.fromCenter(
        center: base.translate(0, -0.03 * scale),
        width: 0.03 * scale,
        height: 0.08 * scale,
      ),
      Paint()..color = const Color(0xFF5B3A2E),
    );
    for (final (dx, dy, rr, color) in const [
      (0.0, -0.12, 0.07, Color(0xFF1F5A3D)),
      (-0.04, -0.09, 0.05, Color(0xFF2A7048)),
      (0.04, -0.09, 0.05, Color(0xFF2A7048)),
      (0.0, -0.16, 0.045, Color(0xFF36855A)),
    ]) {
      canvas.drawCircle(
        base.translate(dx * scale, dy * scale),
        rr * scale,
        Paint()..color = color,
      );
    }
  }
}

/// Paints the [src] region of [artwork] (source units) into [dst] with a
/// uniform scale. [dst] must have the same aspect ratio as [src]; the board
/// layout guarantees this, so tiles are never stretched.
void paintTile(Canvas canvas, PuzzleArtwork artwork, Rect dst, Rect src) {
  final scale = dst.width / src.width;
  assert(
    (dst.height / src.height - scale).abs() < 1e-6 * scale + 1e-9,
    'tile would be stretched',
  );
  canvas.save();
  canvas.clipRect(dst);
  canvas.translate(dst.left - src.left * scale, dst.top - src.top * scale);
  canvas.scale(scale);
  artwork.paint(canvas, artwork.sourceSize);
  canvas.restore();
}
